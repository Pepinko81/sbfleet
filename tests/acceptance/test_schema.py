def file_facts(root):
    # Runtime data directories change naturally. Control-plane files must not.
    return {
        str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in root.rglob("*")
        if p.is_file()
        and "volumes" not in p.parts
        and ".cache" not in p.parts
        and p.suffix in {".json", ".yml", ".env"}
        and not p.is_symlink()
    }


def test_schema_diff_plan_real_managed(disposable_home, capsys):
    root = disposable_home["root"]
    a = create_project(root, "a", start=True)
    b = create_project(root, "b", start=True)
    da = reg.project_dir(root, "a") / "deployment"
    db = reg.project_dir(root, "b") / "deployment"
    sentinel, sentinel_before = _sentinel(disposable_home["run_id"])
    try:
        for dep, meta in ((da, a), (db, b)):
            _psql(dep, meta["compose_project"], BASE)
        first = s.collect_schema(root, "a")
        second = s.collect_schema(root, "b")
        assert first.state == second.state == "KNOWN", (first.error, second.error)
        identical = s.compare(first, second)
        assert not identical.differences, [(d.kind, d.key) for d in identical.differences]
        assert {o.kind for o in first.objects if o.key[0] == "app"} >= {
            "SCHEMA",
            "TABLE",
            "COLUMN",
            "CONSTRAINT",
            "INDEX",
            "FUNCTION",
            "RLS",
            "POLICY",
            "VIEW",
            "MATERIALIZED_VIEW",
            "ENUM",
            "SEQUENCE",
            "TRIGGER",
            "UNSUPPORTED",
        }
        assert any(o.key[0] == "auth" for o in first.objects)
        assert any(o.key[0] == "storage" for o in first.objects)
        domain_column = next(
            o
            for o in first.objects
            if o.kind == "COLUMN" and o.key == ["app", "domain_probe", "value"]
        )
        assert domain_column.facts["nullable"] is False
        _psql(da, a["compose_project"], VARIANT)
        before_a = s.collect_schema(root, "a")
        before_b = s.collect_schema(root, "b")
        before_files = file_facts(root)
        capsys.readouterr()
        assert main(["--home", str(root), "schema", "diff", "a", "b", "--json"]) == 0
        payload = json.loads(capsys.readouterr().out)
        result = s.SchemaDiff.model_validate(payload)
        assert {d.kind for d in result.differences} >= {
            "SCHEMA",
            "TABLE",
            "COLUMN",
            "INDEX",
            "FUNCTION",
            "RLS",
            "POLICY",
        }
        assert main(["--home", str(root), "migrate", "plan", "a", "b", "--json"]) == 0
        plan = s.MigrationPlan.model_validate_json(capsys.readouterr().out)
        assert plan.diff == result
        assert plan.summary["SAFE"] and plan.summary["REVIEW_REQUIRED"]
        assert plan.summary["DESTRUCTIVE"]
        domain_item = next(
            i for i in plan.items if i.difference.key == ["app", "items", "domain_note"]
        )
        assert domain_item.classification == "REVIEW_REQUIRED"
        assert main(["--home", str(root), "schema", "diff", "a", "b"]) == 0
        human = capsys.readouterr().out
        assert "CHANGED" in human and "PARTIAL" in human

        async def exercise():
            server = create_server(root)
            for name in ("schema_diff", "migration_plan"):
                response = await server.call_tool(name, {"source": "a", "target": "b"})
                assert "KNOWN" in str(response)
                assert "private-fixture-secret" not in str(response)

        asyncio.run(exercise())
        assert "private-fixture-secret" not in json.dumps(payload) + plan.model_dump_json() + human
        assert s.collect_schema(root, "a") == before_a
        assert s.collect_schema(root, "b") == before_b
        assert file_facts(root) == before_files
        for dep, meta in ((da, a), (db, b)):
            assert (
                _psql(dep, meta["compose_project"], "SELECT name || amount::text FROM app.items")
                == "sentinel7.00"
            )
        assert (
            _run(
                ["docker", "volume", "inspect", "--format", "{{.Name}}|{{.CreatedAt}}", sentinel]
            ).stdout.strip()
            == sentinel_before
        )
        stop_project(root, "b")
        unavailable = s.schema_diff(root, "a", "b")
        assert unavailable.state == "UNKNOWN" and unavailable.error

        async def unavailable_mcp():
            server = create_server(root)
            for name in ("schema_diff", "migration_plan"):
                response = await server.call_tool(name, {"source": "a", "target": "b"})
                assert "UNKNOWN" in str(response)

        asyncio.run(unavailable_mcp())
    finally:
        _run(["docker", "volume", "rm", sentinel])
